export function matchEmoji(query: string, limit = 8): TxEditorEmoji[] {
  const needle = query.toLowerCase();
  const starts = TX_EDITOR_EMOJI.filter((emoji) => emoji.name.startsWith(needle) || emoji.aliases?.some((alias) => alias.startsWith(needle)));
  const contains = TX_EDITOR_EMOJI.filter((emoji) => !starts.includes(emoji) && (emoji.name.includes(needle) || emoji.aliases?.some((alias) => alias.includes(needle))));
  return [...starts, ...contains].slice(0, limit);
}
